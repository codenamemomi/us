def seed_questions() -> tuple[int, int]:
    inserted = 0
    reactivated = 0
    with SessionLocal.begin() as db:
        for category, text in QUESTIONS:
            question = db.scalar(
                select(Question).where(
                    Question.category == category,
                    Question.text == text,
                )
            )
            if question is None:
                db.add(Question(category=category, text=text, active=True))
                inserted += 1
            elif not question.active:
                question.active = True
                reactivated += 1
    return inserted, reactivated


if __name__ == "__main__":
    inserted_count, reactivated_count = seed_questions()
